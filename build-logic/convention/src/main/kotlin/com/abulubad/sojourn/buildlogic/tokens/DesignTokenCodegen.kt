package com.abulubad.sojourn.buildlogic.tokens

import kotlin.math.roundToInt

/**
 * Turns [DesignTokens] into Kotlin source for `core:designsystem` (ADR 0008).
 *
 * Mapping (documented in docs/design-system/mapping.md):
 * - `color.tokens` → `SojournColors` + `lightSojournColors()` / `darkSojournColors()`
 * - `type.groups[].styles[]` → `SojournType` + `sojournType(display, text)` (numbers only; fonts are hand-maintained)
 * - `spacing` → `SojournSpacing`, `radius` → `SojournShapes`, `size` → `SojournSizes`
 * - `shadow` → `SojournElevation` (elevation = blur / 2, tint = the shadow colour)
 * - `duration` + `easing` → `SojournMotion`
 *
 * Token names map kebab → lowerCamel (`surface-sunken` → `surfaceSunken`). Every generated object exposes `all`,
 * a name → value map, so tests can assert one property per token and the showcase can render every token.
 */
class DesignTokenCodegen(private val tokens: DesignTokens, private val packageName: String) {

    /** File name → content. */
    fun files(): Map<String, String> = mapOf(
        "SojournColors.kt" to colors(),
        "SojournType.kt" to type(),
        "SojournSpacing.kt" to spacing(),
        "SojournShapes.kt" to shapes(),
        "SojournElevation.kt" to elevation(),
        "SojournSizes.kt" to sizes(),
        "SojournMotion.kt" to motion(),
    )

    private fun header(vararg imports: String): String = buildString {
        appendLine("// GENERATED by the sojourn.tokens plugin from design/tokens.json (${tokens.name} v${tokens.version}).")
        appendLine("// Do not edit. Change design/tokens.json and rebuild (ADR 0008).")
        appendLine("@file:Suppress(\"MagicNumber\", \"LongParameterList\", \"MaxLineLength\")")
        appendLine()
        appendLine("package $packageName")
        appendLine()
        imports.sorted().forEach { appendLine("import $it") }
        appendLine()
    }

    private fun colors(): String = buildString {
        append(header("androidx.compose.runtime.Immutable", "androidx.compose.ui.graphics.Color"))
        appendLine("/**")
        appendLine(" * Colour tokens for one theme. Read through `SojournTheme.colors`; never construct in feature code.")
        appendLine(" * Usage notes are the design system's own.")
        appendLine(" */")
        appendLine("@Immutable")
        appendLine("class SojournColors(")
        tokens.colors.forEach { token ->
            appendLine(kdoc(token.usage, indent = "    "))
            appendLine("    val ${token.name.camel()}: Color,")
        }
        appendLine(") {")
        appendLine("    /** Every colour token by its design-system name. */")
        appendLine("    val all: Map<String, Color> = mapOf(")
        tokens.colors.forEach { appendLine("        \"${it.name}\" to ${it.name.camel()},") }
        appendLine("    )")
        appendLine()
        appendLine("    companion object {")
        appendLine("        /** Token names in design-system order, for parity tests. */")
        appendLine("        val tokenNames: List<String> = listOf(")
        tokens.colors.forEach { appendLine("            \"${it.name}\",") }
        appendLine("        )")
        appendLine("    }")
        appendLine("}")
        tokens.themes.forEach { theme ->
            appendLine()
            appendLine("/** The ${theme} theme's colours. */")
            appendLine("fun ${theme}SojournColors(): SojournColors = SojournColors(")
            tokens.colors.forEach { token ->
                appendLine("    ${token.name.camel()} = ${colorLiteral(token.values.getValue(theme))},")
            }
            appendLine(")")
        }
    }

    private fun type(): String = buildString {
        append(
            header(
                "androidx.compose.runtime.Immutable",
                "androidx.compose.ui.text.TextStyle",
                "androidx.compose.ui.text.font.FontFamily",
                "androidx.compose.ui.text.font.FontWeight",
                "androidx.compose.ui.text.style.LineHeightStyle",
                "androidx.compose.ui.unit.em",
                "androidx.compose.ui.unit.sp",
            ),
        )
        appendLine("/** The type scale. Read through `SojournTheme.type`. */")
        appendLine("@Immutable")
        appendLine("class SojournType(")
        tokens.typeStyles.forEach { style ->
            appendLine(kdoc(style.usage, indent = "    "))
            appendLine("    val ${style.name.camel()}: TextStyle,")
        }
        appendLine(") {")
        appendLine("    /** Every text style by its design-system name. */")
        appendLine("    val all: Map<String, TextStyle> = mapOf(")
        tokens.typeStyles.forEach { appendLine("        \"${it.name}\" to ${it.name.camel()},") }
        appendLine("    )")
        appendLine()
        appendLine("    companion object {")
        appendLine("        val styleNames: List<String> = listOf(")
        tokens.typeStyles.forEach { appendLine("            \"${it.name}\",") }
        appendLine("        )")
        appendLine("    }")
        appendLine("}")
        appendLine()
        appendLine("/**")
        appendLine(" * Builds the scale from the two families (${tokens.typeFamilies.joinToString()}). Sizes, line heights,")
        appendLine(" * weights and letter spacing come from the tokens; tabular figures are on for every style (brand book).")
        appendLine(" */")
        appendLine("fun sojournType(${tokens.typeFamilies.joinToString { "$it: FontFamily" }}): SojournType = SojournType(")
        tokens.typeStyles.forEach { style ->
            appendLine("    ${style.name.camel()} = TextStyle(")
            appendLine("        fontFamily = ${style.family},")
            appendLine("        fontSize = ${style.fontSizePx}.sp,")
            appendLine("        lineHeight = ${style.lineHeightPx}.sp,")
            appendLine("        fontWeight = FontWeight(${style.fontWeight}),")
            style.letterSpacingEm?.let { appendLine("        letterSpacing = ($it).em,") }
            appendLine("        fontFeatureSettings = \"tnum\",")
            appendLine("        lineHeightStyle = LineHeightStyle(LineHeightStyle.Alignment.Center, LineHeightStyle.Trim.None),")
            appendLine("    ),")
        }
        appendLine(")")
    }

    private fun spacing(): String = dpObject(
        objectName = "SojournSpacing",
        doc = "Spacing tokens. Side margin is `space4`, section gap `space6`, in-card `space3` (brand book).",
        entries = tokens.spacing,
    )

    private fun sizes(): String = dpObject(
        objectName = "SojournSizes",
        doc = "Size tokens: minimum touch target, icon sizes and bar heights.",
        entries = tokens.sizes,
    )

    private fun dpObject(objectName: String, doc: String, entries: List<SimpleToken>): String = buildString {
        append(header("androidx.compose.ui.unit.Dp", "androidx.compose.ui.unit.dp"))
        appendLine("/** $doc */")
        appendLine("object $objectName {")
        entries.forEach { token ->
            appendLine(kdoc(token.usage, indent = "    "))
            appendLine("    val ${token.name.camel()}: Dp = ${token.value.px()}.dp")
            appendLine()
        }
        appendLine("    /** Every token by its design-system name. */")
        appendLine("    val all: Map<String, Dp> = mapOf(")
        entries.forEach { appendLine("        \"${it.name}\" to ${it.name.camel()},") }
        appendLine("    )")
        appendLine("}")
    }

    private fun shapes(): String = buildString {
        append(
            header(
                "androidx.compose.foundation.shape.RoundedCornerShape",
                "androidx.compose.ui.unit.Dp",
                "androidx.compose.ui.unit.dp",
            ),
        )
        appendLine("/** Corner radii as shapes. `sheetTop` rounds only the top corners of a sheet with the `xl` radius. */")
        appendLine("object SojournShapes {")
        tokens.radius.forEach { token ->
            appendLine(kdoc(token.usage, indent = "    "))
            appendLine("    val ${token.name.camel("radius-")}: RoundedCornerShape = RoundedCornerShape(${token.value.px()}.dp)")
            appendLine()
        }
        val xl = tokens.radius.single { it.name == "radius-xl" }
        appendLine("    /** Top corners of sheets (`radius-xl`). */")
        appendLine("    val sheetTop: RoundedCornerShape = RoundedCornerShape(topStart = ${xl.value.px()}.dp, topEnd = ${xl.value.px()}.dp)")
        appendLine()
        appendLine("    /** Every radius token by its design-system name. */")
        appendLine("    val all: Map<String, Dp> = mapOf(")
        tokens.radius.forEach { appendLine("        \"${it.name}\" to ${it.value.px()}.dp,") }
        appendLine("    )")
        appendLine("}")
    }

    private fun elevation(): String = buildString {
        append(
            header(
                "androidx.compose.runtime.Immutable",
                "androidx.compose.ui.graphics.Color",
                "androidx.compose.ui.unit.Dp",
                "androidx.compose.ui.unit.dp",
            ),
        )
        appendLine("/** One shadow token on Compose: an elevation (half the CSS blur radius) and its tint colour. */")
        appendLine("@Immutable")
        appendLine("class SojournShadow(val elevation: Dp, val color: Color)")
        appendLine()
        appendLine("/** Shadow tokens for one theme. Read through `SojournTheme.elevation`. Elevation is rare (brand book). */")
        appendLine("@Immutable")
        appendLine("class SojournElevation(")
        tokens.shadows.forEach { token ->
            appendLine(kdoc(token.usage, indent = "    "))
            appendLine("    val ${token.name.level()}: SojournShadow,")
        }
        appendLine(") {")
        appendLine("    /** Every shadow token by its design-system name. */")
        appendLine("    val all: Map<String, SojournShadow> = mapOf(")
        tokens.shadows.forEach { appendLine("        \"${it.name}\" to ${it.name.level()},") }
        appendLine("    )")
        appendLine("}")
        tokens.themes.forEach { theme ->
            appendLine()
            appendLine("/** The $theme theme's shadows. */")
            appendLine("fun ${theme}SojournElevation(): SojournElevation = SojournElevation(")
            tokens.shadows.forEach { token ->
                val shadow = parseShadow(token.values.getValue(theme))
                appendLine("    ${token.name.level()} = SojournShadow(elevation = ${shadow.elevationDp}.dp, color = ${colorLiteral(shadow.color)}),")
            }
            appendLine(")")
        }
    }

    private fun motion(): String = buildString {
        append(header("androidx.compose.animation.core.CubicBezierEasing", "androidx.compose.animation.core.Easing"))
        appendLine("/**")
        appendLine(" * Durations (milliseconds) and easings. Nothing runs longer than `slower` (M-02); springs and the")
        appendLine(" * reduce-motion fallback are hand-written extensions in `SojournMotionExtensions.kt` (M-03).")
        appendLine(" */")
        appendLine("object SojournMotion {")
        tokens.durations.forEach { token ->
            appendLine(kdoc(token.usage, indent = "    "))
            appendLine("    const val ${token.name.camel("dur-")}: Int = ${token.value.removeSuffix("ms").trim().toInt()}")
            appendLine()
        }
        tokens.easings.forEach { token ->
            appendLine(kdoc(token.usage, indent = "    "))
            appendLine("    val ${token.name.camel("ease-")}: Easing = ${easingLiteral(token.value)}")
            appendLine()
        }
        appendLine("    /** Every duration token by its design-system name. */")
        appendLine("    val durations: Map<String, Int> = mapOf(")
        tokens.durations.forEach { appendLine("        \"${it.name}\" to ${it.name.camel("dur-")},") }
        appendLine("    )")
        appendLine()
        appendLine("    /** Every easing token by its design-system name. */")
        appendLine("    val easings: Map<String, Easing> = mapOf(")
        tokens.easings.forEach { appendLine("        \"${it.name}\" to ${it.name.camel("ease-")},") }
        appendLine("    )")
        appendLine("}")
    }

    // --- literals -------------------------------------------------------------------------------------------

    private class Shadow(val elevationDp: Int, val color: String)

    /** `0 8px 24px rgba(27, 36, 33, 0.16)` → elevation 12dp, tint rgba(...). */
    private fun parseShadow(value: String): Shadow {
        val match = SHADOW.matchEntire(value.trim()) ?: error("Unsupported shadow value '$value'")
        val blur = match.groupValues[2].toInt()
        return Shadow(elevationDp = (blur / 2.0).roundToInt(), color = match.groupValues[3])
    }

    private fun easingLiteral(value: String): String {
        val match = BEZIER.matchEntire(value.trim()) ?: error("Unsupported easing value '$value'")
        val points = match.groupValues[1].split(',').map { it.trim().toFloat() }
        require(points.size == 4) { "cubic-bezier needs four control values: '$value'" }
        return "CubicBezierEasing(${points.joinToString { it.literal() }})"
    }

    private fun kdoc(usage: String, indent: String): String =
        "$indent/** ${usage.replace("*/", "*&#47;").trim()} */"

    private companion object {
        val SHADOW = Regex("""^0 (\d+)px (\d+)px (rgba\([^)]*\))$""")
        val BEZIER = Regex("""^cubic-bezier\(([^)]*)\)$""")
        val HEX = Regex("""^#([0-9a-fA-F]{6})$""")
        val RGBA = Regex("""^rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([0-9.]+)\s*\)$""")

        /** `#faf7f2` → `Color(0xFFFAF7F2)`; `rgba(13, 20, 18, 0.56)` → `Color(red = 13, green = 20, blue = 18, alpha = 143)`. */
        fun colorLiteral(value: String): String {
            HEX.matchEntire(value.trim())?.let { return "Color(0xFF${it.groupValues[1].uppercase()})" }
            RGBA.matchEntire(value.trim())?.let {
                val (r, g, b, a) = it.destructured
                val alpha = (a.toDouble() * 255).roundToInt()
                return "Color(red = $r, green = $g, blue = $b, alpha = $alpha)"
            }
            error("Unsupported colour value '$value'")
        }

        fun Float.literal(): String = if (this == toInt().toFloat()) "${toInt()}f" else "${this}f"

        /** `surface-sunken` → `surfaceSunken`; with [strip], `radius-xs` → `xs`. */
        fun String.camel(strip: String = ""): String {
            val parts = removePrefix(strip).split('-').filter { it.isNotEmpty() }
            return parts.first() + parts.drop(1).joinToString("") { part ->
                part.replaceFirstChar { it.titlecase() }
            }
        }

        /** `shadow-1` → `level1`. */
        fun String.level(): String = "level" + removePrefix("shadow-")
    }
}
